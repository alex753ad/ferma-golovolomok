// Заменить меши Kenney своими деталями. Узел-меш превращается в пустой узел с тем же именем — анимации его находят.
export function dress(key, scene) {
  if (!DRESS[key]) return;
  const meshes = [];
  scene.traverse(o => o.isMesh && meshes.push(o));
  for (const m of meshes) {
    const o = new THREE.Object3D();
    o.name = m.name; o.position.copy(m.position); o.quaternion.copy(m.quaternion); o.scale.copy(m.scale);
    m.parent.add(o);
    [...m.children].forEach(c => o.add(c));
    m.removeFromParent();
  }
  const n = {};
  scene.traverse(o => { if (o.name) n[o.name] = o; });
  DRESS[key](n);
  bake(scene);
}
