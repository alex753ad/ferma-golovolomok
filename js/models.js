function tree(trunkH, trunkR, blobs, trunk = BARK) {
  const g = G();
  cyl(g, trunk, [trunkR * 0.75, trunkR, trunkH], [0, trunkH / 2, 0], { seg: 6 });
  for (const s of [1, -1]) part(g, trunk, [trunkR * 1.2, trunkR * 0.7, trunkR * 0.6], [s * trunkR * 0.9, 0.08, s * 0.05], { k: 0.4, rz: s * 0.5 }); // корни
  for (const [x, y, z, s, c] of blobs) part(g, c, [s, s * 0.85, s], [x, y, z], { k: 0.7, ry: x * 2 });
  return g;
}
