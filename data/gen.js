function gcd(a, b) { return b ? gcd(b, a % b) : a; }

// Генератор случайных чисел по зерну (всегда одинаковая последовательность)
export function rng(seed) {
  let x = 0;
  for (const c of String(seed)) x = Math.imul(x ^ c.charCodeAt(0), 2654435761) >>> 0;
  const next = () => { x = (x + 0x6D2B79F5) >>> 0; let t = Math.imul(x ^ x >>> 15, 1 | x); t ^= t + Math.imul(t ^ t >>> 7, 61 | t); return ((t ^ t >>> 14) >>> 0) / 4294967296; };
  return { next, int: (a, b) => a + Math.floor(next() * (b - a + 1)), pick: list => list[Math.floor(next() * list.length)] };
}

// Задача по id 'g<шаблон>-<зерно>'
export function genTask(id) {
  const m = /^g(\d+)-(.+)$/.exec(id);
  if (!m || !TEMPLATES[+m[1]]) return null;
  return { id, ...TEMPLATES[+m[1]](rng(id)) };
}
// Новая задача из шаблонов: шаблон выбирается по зерну
export function genId(seed) { return `g${rng('t' + seed).int(0, TEMPLATES.length - 1)}-${seed}`; }
